"""Initial PostgreSQL schema (same tables as the SQLite schema in storage.py, SEC-01 included)

Revision ID: 0001_initial
Revises:
Create Date: 2026-11-20

Timestamps stay ISO-8601 text in UTC, as in SQLite, so every query and the data move (APP-03)
work the same on both engines. Ids are identity columns BY DEFAULT, so APP-03 can copy rows
with their original ids and then move the sequences past them.
"""
from __future__ import annotations

from alembic import op

revision = "0001_initial"
down_revision = None
branch_labels = None
depends_on = None

ID = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"

TABLES = [
    f"""CREATE TABLE users (
        id             {ID},
        username       TEXT NOT NULL,
        password_hash  TEXT NOT NULL,
        role           TEXT NOT NULL CHECK (role IN ('recruiter', 'admin')),
        active         INTEGER NOT NULL DEFAULT 1,
        created_at     TEXT NOT NULL,
        last_login_at  TEXT,
        email          TEXT,
        totp_secret    TEXT,
        totp_last_step BIGINT,
        recovery_codes TEXT
    )""",
    "CREATE UNIQUE INDEX users_username_lower ON users (lower(username))",
    f"""CREATE TABLE sessions (
        id          {ID},
        title       TEXT NOT NULL,
        language    TEXT NOT NULL DEFAULT 'ru',
        created_at  TEXT NOT NULL,
        updated_at  TEXT NOT NULL,
        owner_id    BIGINT REFERENCES users(id) ON DELETE SET NULL
    )""",
    "CREATE INDEX idx_sessions_owner ON sessions (owner_id, updated_at DESC)",
    f"""CREATE TABLE vacancies (
        id          {ID},
        session_id  BIGINT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
        title       TEXT NOT NULL,
        text        TEXT NOT NULL,
        bias_json   TEXT,
        created_at  TEXT NOT NULL
    )""",
    "CREATE INDEX idx_vacancies_session ON vacancies (session_id)",
    f"""CREATE TABLE resumes (
        id           {ID},
        session_id   BIGINT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
        filename     TEXT NOT NULL,
        sha256       TEXT NOT NULL,
        text         TEXT NOT NULL DEFAULT '',
        status       TEXT NOT NULL,
        error        TEXT,
        profile_json TEXT,
        created_at   TEXT NOT NULL,
        analyzed_at  TEXT,
        started_at   TEXT,
        UNIQUE (session_id, sha256)
    )""",
    "CREATE INDEX idx_resumes_session_status ON resumes (session_id, status)",
    "CREATE INDEX idx_resumes_pending ON resumes (status) WHERE status = 'pending'",
    """CREATE TABLE demographics (
        resume_id   BIGINT PRIMARY KEY REFERENCES resumes(id) ON DELETE CASCADE,
        gender      TEXT NOT NULL DEFAULT 'unknown',
        age         INTEGER
    )""",
    """CREATE TABLE scores (
        resume_id    BIGINT NOT NULL REFERENCES resumes(id) ON DELETE CASCADE,
        vacancy_id   BIGINT NOT NULL REFERENCES vacancies(id) ON DELETE CASCADE,
        score        INTEGER NOT NULL,
        verdict      TEXT NOT NULL,
        summary      TEXT NOT NULL,
        details_json TEXT NOT NULL,
        created_at   TEXT NOT NULL,
        PRIMARY KEY (resume_id, vacancy_id)
    )""",
    "CREATE INDEX idx_scores_vacancy ON scores (vacancy_id, score DESC)",
    """CREATE TABLE settings (
        key         TEXT PRIMARY KEY,
        value       TEXT NOT NULL,
        updated_at  TEXT NOT NULL
    )""",
    f"""CREATE TABLE audit_log (
        id          {ID},
        created_at  TEXT NOT NULL,
        user_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
        username    TEXT,
        action      TEXT NOT NULL,
        session_id  BIGINT,
        detail      TEXT
    )""",
    "CREATE INDEX idx_audit_created ON audit_log (created_at DESC, id DESC)",
    """CREATE TABLE candidate_status (
        vacancy_id  BIGINT NOT NULL REFERENCES vacancies(id) ON DELETE CASCADE,
        resume_id   BIGINT NOT NULL REFERENCES resumes(id) ON DELETE CASCADE,
        status      TEXT NOT NULL,
        note        TEXT NOT NULL DEFAULT '',
        updated_at  TEXT NOT NULL,
        updated_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
        PRIMARY KEY (vacancy_id, resume_id)
    )""",
    f"""CREATE TABLE llm_usage (
        id          {ID},
        user_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
        kind        TEXT NOT NULL,
        created_at  TEXT NOT NULL
    )""",
    "CREATE INDEX idx_llm_usage_user ON llm_usage (user_id, kind, created_at)",
    """CREATE TABLE password_resets (
        token_hash  TEXT PRIMARY KEY,
        user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        created_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
        created_at  TEXT NOT NULL,
        expires_at  TEXT NOT NULL,
        used_at     TEXT
    )""",
]

DROP_ORDER = ["password_resets", "llm_usage", "candidate_status", "audit_log", "settings", "scores",
              "demographics", "resumes", "vacancies", "sessions", "users"]


def upgrade() -> None:
    for statement in TABLES:
        op.execute(statement)


def downgrade() -> None:
    for table in DROP_ORDER:
        op.execute(f"DROP TABLE IF EXISTS {table}")
